//! Internationalization (i18n) and localization support for TextCraft UI.

use crate::ui::state::AppLanguage;

/// Translates a UI label, tooltip, or message according to the active language.
/// If the text has no translation or the language is English, returns the original text.
pub fn tr(language: AppLanguage, text: &'static str) -> &'static str {
    match language {
        AppLanguage::English => text,
        AppLanguage::Portuguese => translate_pt(text).unwrap_or(text),
        AppLanguage::Spanish => translate_es(text).unwrap_or(text),
        AppLanguage::French => translate_fr(text).unwrap_or(text),
        AppLanguage::German => translate_de(text).unwrap_or(text),
        AppLanguage::Italian => translate_it(text).unwrap_or(text),
    }
}

/// Translates dynamic strings that are constructed at runtime.
#[allow(dead_code)]
pub fn tr_dynamic(language: AppLanguage, text: &str) -> String {
    match language {
        AppLanguage::English => text.to_string(),
        AppLanguage::Portuguese => translate_pt(text)
            .map(|s| s.to_string())
            .unwrap_or_else(|| text.to_string()),
        AppLanguage::Spanish => translate_es(text)
            .map(|s| s.to_string())
            .unwrap_or_else(|| text.to_string()),
        AppLanguage::French => translate_fr(text)
            .map(|s| s.to_string())
            .unwrap_or_else(|| text.to_string()),
        AppLanguage::German => translate_de(text)
            .map(|s| s.to_string())
            .unwrap_or_else(|| text.to_string()),
        AppLanguage::Italian => translate_it(text)
            .map(|s| s.to_string())
            .unwrap_or_else(|| text.to_string()),
    }
}

