//! Internationalization (i18n) and localization support for TextCraft UI.

use crate::ui::state::AppLanguage;

/// Translates a UI label, tooltip, or message according to the active language.
/// If the text has no translation or the language is English, returns the original text.
pub fn tr(language: AppLanguage, text: &'static str) -> &'static str {
    match language {
        AppLanguage::English => text,
        AppLanguage::Portuguese => translate_pt(text),
        AppLanguage::Spanish => translate_es(text),
        AppLanguage::French => translate_fr(text),
        AppLanguage::German => translate_de(text),
        AppLanguage::Italian => translate_it(text),
    }
}

